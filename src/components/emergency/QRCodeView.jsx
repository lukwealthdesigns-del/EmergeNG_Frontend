import { useEffect, useState } from "react";
import QRCode from "qrcode";
import { Spinner } from "../ui";
import { useI18n } from "../../i18n";

const OPTS = { errorCorrectionLevel: "M", margin: 2, color: { dark: "#000000", light: "#ffffff" } };

/** Renders a QR code entirely on this device (no network). The code is always dark-on-white, whatever the theme, so scanners can read it. */
export default function QRCodeView({ text, size = 288, onError, className = "" }) {
  const { t } = useI18n(); const [svg, setSvg] = useState(null); const [err, setErr] = useState(false);
  useEffect(() => {
    let off = false; setErr(false);
    if (!text) { setSvg(null); return; }
    QRCode.toString(text, { ...OPTS, type: "svg" }).then((s) => { if (!off) setSvg(s); }).catch((e) => { if (!off) { setErr(true); setSvg(null); onError?.(e); } });
    return () => { off = true; };
  }, [text]); // eslint-disable-line react-hooks/exhaustive-deps
  if (err) return null;
  if (!svg) return text ? <div className="grid place-items-center" style={{ width: size, height: size }}><Spinner /></div> : null;
  // The SVG string is generated by the qrcode library from our text: it contains only <path> geometry, never the text itself.
  return <div role="img" aria-label={t("qr.alt")} className={`qr-tile rounded-3xl bg-white p-2 shadow-soft ${className}`} style={{ width: size, height: size }} dangerouslySetInnerHTML={{ __html: svg.replace("<svg ", `<svg width="100%" height="100%" `) }} />;
}

export const qrToPngDataUrl = (text, width = 720) => QRCode.toDataURL(text, { ...OPTS, width, margin: 3 });
